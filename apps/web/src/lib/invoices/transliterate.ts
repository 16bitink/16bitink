/** Characters Helvetica can draw: printable ASCII and Latin-1. */
const DRAWABLE = /^[\x20-\x7e\xa0-\xff]$/;

const stripMarks = (ch: string): string => ch.normalize('NFD').replace(/[̀-ͯ]/g, '');

/** One character as Helvetica can draw it: kept, mapped, stripped of its accents, or dropped. */
function drawable(ch: string): string {
  if (DRAWABLE.test(ch)) return ch;
  const mapped = charMap[ch];
  if (mapped !== undefined) return mapped;
  const plain = stripMarks(ch);
  return [...plain].every((c) => DRAWABLE.test(c)) ? plain : '';
}

/** Text safe to print with the PDF's built-in font: punctuation is kept (addresses need it). */
export function transliterate(text: string): string {
  return [...text].map(drawable).join('').replace(/\s+/g, ' ').trim();
}
