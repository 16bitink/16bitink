"""Writes src/art/manifest.ts from the sprite size tables (run after build_sprites / build_backdrops)."""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
sizes = {**json.load(open(HERE / 'sizes.json')), **json.load(open(HERE / 'sizes-backdrops.json'))}
OUT = HERE.parent.parent / 'src' / 'art' / 'manifest.ts'

lines = []
for k in sorted(sizes):
    w, h = sizes[k]
    ext = 'webp' if k.startswith('bg-') or k == 'map' else 'png'
    logical = k.startswith('bg-') or k == 'map'
    lw, lh = (w, h) if logical else (w / 2, h / 2)
    lines.append(f"  '{k}': {{ file: '{k}.{ext}', w: {w}, h: {h}, lw: {lw:g}, lh: {lh:g} }},")

OUT.write_text('''/// <reference types="vite/client" />
// Generated by dev/art/gen_manifest.py - do not edit by hand.
// Every key -> its image file in ./img plus its size: w x h in image px, lw x lh in board-logical px
// (sprites are drawn at 2x the 540 x 960 board, so logical = image / 2; backgrounds and the map are
// full-screen images and are given in image px only).

export interface ArtEntry {
  readonly file: string;
  readonly w: number;
  readonly h: number;
  readonly lw: number;
  readonly lh: number;
}

const ART = {
''' + chr(10).join(lines) + '''
} as const satisfies Record<string, ArtEntry>;

export type ArtKey = keyof typeof ART;

const urls = import.meta.glob<string>('./img/*.{png,webp}', { query: '?url', import: 'default', eager: true });

/** Raft body is 90 logical px (180 image px) wide and sits at x 0 of every `skip-*` sprite. */
export const SKIP_RAFT_WIDTH = 180;
export const MILESTONE_RAFTS = [3, 7, 14, 30, 50, 100] as const;
export const MILESTONE_TRAILS = [3, 7, 14, 30, 50, 100] as const;
export const SKIP_POSES = ['aim', 'idle', 'cheer', 'shrug'] as const;
export const BRUMM_POSES = ['smug', 'hit', 'defeated'] as const;
export const CHAPTER_BACKGROUNDS = [1, 2, 3, 4, 5] as const;
export const BRICK_KINDS = [
  'soft-1', 'soft-2', 'soft-3', 'tough-1', 'tough-2', 'tough-3', 'stone', 'x3', 'keg', 'pickup',
  'ice-1', 'ice-2', 'key', 'gate', 'dense',
] as const;

/** Where each chapter's place sits on the 1920 x 1080 coast map (`map`), in image px. */
export const MAP_POINTS = [
  { x: 225, y: 390 }, { x: 600, y: 495 }, { x: 960, y: 435 }, { x: 1350, y: 435 }, { x: 1755, y: 405 },
] as const;

export const art: { readonly [K in ArtKey]: ArtEntry & { readonly url: string } } = Object.fromEntries(
  Object.entries(ART).map(([key, entry]) => {
    const url = urls[`./img/${entry.file}`];
    if (url === undefined) throw new Error(`InkBrick art: missing file ${entry.file} for "${key}"`);
    return [key, { ...entry, url }];
  }),
) as { readonly [K in ArtKey]: ArtEntry & { readonly url: string } };

export const ART_KEYS = Object.keys(ART) as readonly ArtKey[];
''')
print(len(sizes), 'entries')
