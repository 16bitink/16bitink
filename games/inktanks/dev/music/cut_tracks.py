#!/usr/bin/env python3
"""Cuts PixelLab music takes into the game's tracks. Each take comes from make_music_loop with loop points
(play to END, jump back to START); the loop's last FADE seconds are crossfaded (equal power) into the sound
that led into START so the end flows into the start, the file keeps PAD seconds of loop on either side (what an MP3
encoder adds never reaches the loop) and drops the intro, so files stay small. Writes src/audio/music/<id>.mp3
(mono 64k) and src/audio/tracks.ts.
  python3 dev/music/cut_tracks.py   -> reads dev/music/raw/<id>.mp3 and the points in TRACKS below
A track with no points (the victory theme) is trimmed to TAIL seconds and plays once."""
from __future__ import annotations
import subprocess

import numpy as np
from pathlib import Path

HERE = Path(__file__).resolve().parent
GAME = HERE.parents[1]
OUT = GAME / 'src' / 'audio' / 'music'
PAD = 0.5
RATE = 44100
# The crossfade baked into the end of each loop, seconds.
FADE = 0.12
# id -> (loop start s, loop end s) as get_music reports them, or None for a track that plays once.
TRACKS = {}
exec((HERE / 'points.py').read_text())


def decode(src: Path) -> np.ndarray:
    raw = subprocess.run(['ffmpeg', '-v', 'error', '-i', str(src), '-f', 'f32le', '-ac', '1', '-ar', str(RATE), '-'], check=True, capture_output=True).stdout
    return np.frombuffer(raw, dtype=np.float32).copy()


def encode(x: np.ndarray, dst: Path) -> None:
    subprocess.run(['ffmpeg', '-v', 'error', '-y', '-f', 'f32le', '-ac', '1', '-ar', str(RATE), '-i', '-', '-b:a', '64k', str(dst)], input=x.astype(np.float32).tobytes(), check=True)


def cut(track: str, points: tuple[float, float] | None) -> tuple[float, float | None]:
    src, dst = HERE / 'raw' / f'{track}.mp3', OUT / f'{track}.mp3'
    if points is None:
        encode(decode(src), dst)
        return 0.0, None
    x = decode(src)
    a, b, fade, pad = int(points[0] * RATE), int(points[1] * RATE), int(FADE * RATE), int(PAD * RATE)
    loop = x[a:b].copy()
    # Equal-power: the loop's last stretch gives way to the sound that led into its start, so the end flows into the start.
    u = np.linspace(0, 1, fade, dtype=np.float32)
    loop[-fade:] = loop[-fade:] * np.cos(u * np.pi / 2) + x[a - fade:a] * np.sin(u * np.pi / 2)
    encode(np.concatenate([loop[-pad:], loop, loop[:pad]]), dst)
    return PAD, PAD + len(loop) / RATE


def main() -> None:
    OUT.mkdir(exist_ok=True)
    cuts = {t: cut(t, p) for t, p in TRACKS.items()}
    ids = list(cuts)
    lines = ['// Generated by dev/music/cut_tracks.py: do not edit by hand.']
    lines += [f"import {t} from './music/{t}.mp3?url';" for t in ids]
    lines += ['', f"export type TrackId = {' | '.join(repr(t) for t in ids)};", '']
    lines += ['/** Each track, with the seconds its loop runs between (loopEnd null: it plays once). */']
    lines += ['export const MUSIC_TRACKS: Readonly<Record<TrackId, { readonly url: string; readonly loopStart: number; readonly loopEnd: number | null }>> = {']
    lines += [f'  {t}: {{ url: {t}, loopStart: {a:.3f}, loopEnd: {"null" if b is None else f"{b:.3f}"} }},' for t, (a, b) in cuts.items()]
    lines += ['};', '']
    (GAME / 'src' / 'audio' / 'tracks.ts').write_text('\n'.join(lines))
    for t in ids:
        print(f'{t}: {(OUT / f"{t}.mp3").stat().st_size // 1024} KB')


if __name__ == '__main__':
    main()
